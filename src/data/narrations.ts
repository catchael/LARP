// 統一索引：方便依 actId 一次撈整段劇情內文
// ──────────────────────────────────────────────────────────

export const NARRATION_REGISTRY: Record<string, NarrationParagraph[]> = {
  script1_prologue: NARRATIONS_SCRIPT1_PROLOGUE,
  script1_act2: NARRATIONS_SCRIPT1_ACT2,
};

/**
 * 依 actId + paragraph id 取得單段內文。
 * 找不到時回傳空字串，避免崩潰。
 */
export function getNarrationText(actId: string, paragraphId: string): string {
  const list = NARRATION_REGISTRY[actId];
  if (!list) return '';
  return list.find(p => p.id === paragraphId)?.text ?? '';
}